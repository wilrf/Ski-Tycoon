/**
 * Tunes the range generator's knobs so generated faces match each range's real game-scale statistics.
 *
 *   npx tsx tools/terrain-fit/fit.ts alps rockies ...   fit those ranges (all when none given), one result file each
 *   npx tsx tools/terrain-fit/fit.ts --merge           write src/data/rangeParams.ts from the result files
 *
 * Score: mean over stats of ((generated mean - real mean) / real spread)^2, with generated stats averaged over three
 * seeds so no candidate wins by luck on one mountain. Search: 100 random candidates, then a pattern search that
 * nudges one knob at a time from the best, halving the nudge whenever a full sweep finds nothing better.
 */
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { generateRangeGrid } from '../../src/sim/rangeTerrain';
import { isRangeKey, RANGE_KEYS, type RangeKey, type RangeParams } from '../../src/sim/ranges';
import { createRng, nextFloat } from '../../src/sim/rng';
import { faceGrid } from './grids';
import { measure, STAT_NAMES, type Stats } from './stats';

const RESULTS = join(import.meta.dirname, '../terrain-stats/results');
const FITS = join(RESULTS, 'fit');
const SEEDS = [11, 22, 33];
const RANDOM = 100, MAX_EVALS = 400;

const BOUNDS: Record<keyof RangeParams, readonly [number, number]> = {
  relief: [150, 1400], profile: [0.7, 2.5], ridged: [0, 1], gain: [0.3, 0.7], spurs: [0, 0.5],
  incision: [0, 6], creep: [0, 0.5], talus: [25, 60], bench: [0, 1],
};
const KNOBS = Object.keys(BOUNDS) as (keyof RangeParams)[];

type Target = Record<string, { mean: number; sd: number }>;

function generatedStats(p: RangeParams): Stats {
  const all = SEEDS.map((s) => measure(faceGrid(generateRangeGrid(s, p))));
  return Object.fromEntries(STAT_NAMES.map((k) => [k, all.reduce((a, r) => a + r[k], 0) / all.length])) as Stats;
}

const zScores = (s: Stats, t: Target): Record<string, number> =>
  Object.fromEntries(STAT_NAMES.map((k) => [k, (s[k] - t[k]!.mean) / t[k]!.sd]));
const loss = (z: Record<string, number>): number => Object.values(z).reduce((a, v) => a + v * v, 0) / STAT_NAMES.length;

const clampTo = (p: RangeParams): RangeParams =>
  Object.fromEntries(KNOBS.map((k) => [k, Math.min(BOUNDS[k][1], Math.max(BOUNDS[k][0], p[k]))])) as unknown as RangeParams;

function fit(key: RangeKey, target: Target): { params: RangeParams; loss: number; z: Record<string, number>; evals: number } {
  const rng = createRng(KNOBS.length * 7919 + RANGE_KEYS.indexOf(key));
  let evals = 0;
  const score = (p: RangeParams): number => (evals++, loss(zScores(generatedStats(p), target)));
  let best = { p: clampTo(Object.fromEntries(KNOBS.map((k) => [k, (BOUNDS[k][0] + BOUNDS[k][1]) / 2])) as unknown as RangeParams), l: Infinity };
  best.l = score(best.p);
  for (let i = 0; i < RANDOM; i++) {
    const p = Object.fromEntries(KNOBS.map((k) => [k, BOUNDS[k][0] + nextFloat(rng) * (BOUNDS[k][1] - BOUNDS[k][0])])) as unknown as RangeParams;
    const l = score(p);
    if (l < best.l) best = { p, l };
  }
  for (let frac = 0.2; frac > 0.01 && evals < MAX_EVALS; frac /= 2) {
    let improved = true;
    while (improved && evals < MAX_EVALS) {
      improved = false;
      for (const k of KNOBS)
        for (const dir of [1, -1]) {
          const p = clampTo({ ...best.p, [k]: best.p[k] + dir * frac * (BOUNDS[k][1] - BOUNDS[k][0]) });
          if (p[k] === best.p[k]) continue;
          const l = score(p);
          if (l < best.l) { best = { p, l }; improved = true; }
        }
    }
    console.log(`${key}: nudge ${(frac * 100).toFixed(1)}%  loss ${best.l.toFixed(3)}  evals ${evals}`);
  }
  const rounded = Object.fromEntries(KNOBS.map((k) => [k, +best.p[k].toPrecision(3)])) as unknown as RangeParams;
  const z = zScores(generatedStats(rounded), target);
  return { params: rounded, loss: loss(z), z, evals };
}

function merge(): void {
  const fits = Object.fromEntries(readdirSync(FITS).filter((f) => f.endsWith('.json')).map((f) => [f.replace('.json', ''), JSON.parse(readFileSync(join(FITS, f), 'utf8'))]));
  const missing = RANGE_KEYS.filter((k) => !fits[k]);
  if (missing.length) throw new Error(`no fit yet for ${missing.join(', ')}`);
  const rows = RANGE_KEYS.map((k) => `  ${k}: ${JSON.stringify(fits[k].params).replace(/"(\w+)":/g, '$1: ').replace(/,/g, ', ')},`).join('\n');
  writeFileSync(join(import.meta.dirname, '../../src/data/rangeParams.ts'),
    '// Generated by tools/terrain-fit/fit.ts --merge. Do not edit by hand.\n' +
    '// Each range\'s knobs were tuned so generated faces match real faces sampled from Copernicus GLO-30 elevation data.\n' +
    "import type { RangeKey, RangeParams } from '../sim/ranges';\n\n" +
    `export const RANGE_PARAMS: Readonly<Record<RangeKey, RangeParams>> = {\n${rows}\n};\n`);
  writeFileSync(join(RESULTS, 'fit-report.json'), JSON.stringify(Object.fromEntries(RANGE_KEYS.map((k) => [k, { loss: fits[k].loss, z: fits[k].z }])), null, 1));
  console.log('wrote src/data/rangeParams.ts');
}

const args = process.argv.slice(2);
if (args.includes('--merge')) merge();
else {
  const targets = JSON.parse(readFileSync(join(RESULTS, 'game-targets.json'), 'utf8'));
  mkdirSync(FITS, { recursive: true });
  for (const key of args.length ? args.filter(isRangeKey) : RANGE_KEYS) {
    const result = fit(key, targets[key].stats);
    writeFileSync(join(FITS, `${key}.json`), JSON.stringify(result, null, 1));
    console.log(`${key}: done, loss ${result.loss.toFixed(3)}`, JSON.stringify(result.params));
  }
}
